int main(int argc, char const *argv[]) {
    char *pn = strdup(argv[0]);
    program_name = strdup(basename(pn));
    free(pn);

    const char *from = 0;
    const char *out_dir = 0;
    bool emit_schema = false;
    for (int i = 1; i < argc; ++i) {
        if (strcmp(argv[i], "--from") == 0 && i + 1 < argc) {
            from = argv[++i];
        }
        else if (strcmp(argv[i], "--out") == 0 && i + 1 < argc) {
            out_dir = argv[++i];
        }
        else if (strcmp(argv[i], "--sql") == 0) {
            emit_schema = true;
        }
        else if (strcmp(argv[i], "--help") == 0 || strcmp(argv[i], "-h") == 0) {
            std::cerr << "Usage: cw-scaffold --from file.cw [--out dir] [--sql]\n";
            return 0;
        }
        else {
            std::cerr << "Unknown argument: " << argv[i] << "\n";
            return 2;
        }
    }
    if (!from) {
        std::cerr << "cw-scaffold: --from is required\n";
        return 2;
    }

    zmq::context_t *context = new zmq::context_t;
    MessagingInterface::setContext(context);
    Logger::instance();
    MessageLog::setMaxMemory(10000);
    boost::condition_variable_any cond;
    boost::shared_mutex mutex;
    SharedThreadSafeQueue<Package *> queue(cond, mutex);
    Dispatcher::create(queue);
    Scheduler::instance();

    set_parse_only(1);
    std::list<std::string> files;
    files.push_back(from);
    int rc = loadConfig(files);
    if (rc) {
        return rc;
    }

    int n = 0;
    std::list<MachineClass *>::const_iterator it = MachineClass::all_machine_classes.begin();
    while (it != MachineClass::all_machine_classes.end()) {
        MachineClass *mc = *it++;
        if (!mc || !mc->is_record) {
            continue;
        }
        ++n;
        std::string generated;
        {
            std::ostringstream oss;
            emit_interface(oss, mc);
            generated = oss.str();
        }
        if (out_dir) {
            boost::filesystem::create_directories(out_dir);
            std::string path = std::string(out_dir) + "/" + mc->name + "INTERFACE.lpc";
            std::ofstream ofs(path.c_str());
            if (!ofs) {
                std::cerr << "cw-scaffold: cannot write " << path << "\n";
                return 1;
            }
            ofs << generated;
            if (emit_schema) {
                std::string spath = std::string(out_dir) + "/" + mc->name + ".sql";
                std::ofstream sfs(spath.c_str());
                if (!sfs) {
                    std::cerr << "cw-scaffold: cannot write " << spath << "\n";
                    return 1;
                }
                emit_sql(sfs, mc);
            }
        }
        else {
            std::cout << generated;
            if (emit_schema) {
                emit_sql(std::cout, mc);
            }
        }
    }
    if (n == 0) {
        std::cerr << "cw-scaffold: no RECORD classes in " << from << "\n";
        return 2;
    }
    return 0;
}
